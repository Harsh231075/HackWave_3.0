import assert from 'node:assert/strict'
import { createServer } from 'vite'
const { chromium } = await import(process.env.ORLO_PLAYWRIGHT_MODULE || 'playwright')
const server = await createServer({ server: { host: '127.0.0.1', port: 0 } })
await server.listen()
const browser = await chromium.launch({ headless: true, ...(process.env.ORLO_CHROME_PATH ? { executablePath: process.env.ORLO_CHROME_PATH } : {}) })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
  page.setDefaultTimeout(15000)
  const errors = [], requests = []
  page.on('pageerror', error => errors.push(error.message))
  const { fallbackComponentIntent } = await server.ssrLoadModule('/src/domain/componentIntent.ts')
  await page.route('**/api/workspace/resolve', async route => {
    const input = route.request().postDataJSON(); requests.push(input)
    await route.fulfill({json: fallbackComponentIntent(input)})
  })
  const base = 'http://127.0.0.1:' + server.httpServer.address().port
  await page.goto(base)
  await page.waitForSelector('[data-instance-id]')
  const {INITIAL_TASKS,INITIAL_EVENTS}=await server.ssrLoadModule('/server/fixtures/demo.ts')
  await page.evaluate(async data => {
    const s = await import('/src/services/index.ts')
    const {makeInstance} = await import('/src/domain/widgetInstances.ts')
    const {emptyWorkspace} = await import('/src/domain/workspaceDocument.ts')
    const {workspaceDocumentStore} = await import('/src/services/workspaceDocumentStore.ts')
    const {freshLocalData}=await import('/src/services/localDataService.ts')
    assertSaved(s.browserDatabase.replaceAll(data.records,freshLocalData()))
    function assertSaved(result) { if(result.status!=='saved') throw new Error('Fixture records could not be saved') }
    s.noteService.create({title:'Layout continuity',body:'Original text'})
    s.extensionService.setEnabled('quick-timer', true); s.extensionService.setEnabled('calculator', true)
    workspaceDocumentStore(s.browserDatabase).save({...emptyWorkspace(),active:[makeInstance('tasks',undefined,{taskView:'list'}),makeInstance('quick-timer'),makeInstance('outline'),makeInstance('calendar'),makeInstance('calculator')]})
  }, {records:{tasks:INITIAL_TASKS,events:INITIAL_EVENTS,drafts:{},dismissed:[],activity:[]}})
  const doc = () => page.evaluate(async () => (await import('/src/services/workspaceDocumentStore.ts')).workspaceDocumentStore((await import('/src/services/index.ts')).browserDatabase).getSnapshot().document)
  const card = type => page.locator('[data-workspace-component="'+type+'"]')
  const initial = await doc(), taskId=initial.active[0].instanceId
  async function submit(goal, status='ready') {
    await page.keyboard.press('Control+k')
    await page.getByRole('textbox',{name:'Describe the workspace you need'}).fill(goal)
    await page.getByRole('button',{name:'Build workspace'}).click()
    await page.waitForFunction(status => JSON.parse(localStorage.getItem('orlo-browser-db-v2')).collections.workspaceDocument.turns.at(-1)?.status === status,status)
  }
  await card('quick-timer').getByLabel('Timer duration').fill('1')
  await card('quick-timer').getByRole('button',{name:'Start',exact:true}).click()
  const timerBefore = await page.evaluate(async () => (await import('/src/services/index.ts')).timerService.get())
  await submit('Put timer left of tasks')
  let timerBox=await card('quick-timer').boundingBox(), taskBox=await card('tasks').boundingBox()
  assert.ok(timerBox.x+timerBox.width<=taskBox.x+1)
  assert.ok(Math.abs(timerBox.y-taskBox.y)<2)
  assert.ok(timerBox.width<=340)
  assert.equal(requests.at(-1).canvas.width>800,true)
  await card('tasks').getByLabel('Task view',{exact:true}).click()
  await page.getByRole('option',{name:'Kanban',exact:true}).click()
  await submit('Use Tasks version 2')
  assert.equal((await doc()).active.find(w=>w.widgetType==='tasks').viewState.taskView,'kanban')
  assert.equal(await card('tasks').getAttribute('data-layout-version'),'2')
  await submit('Make Tasks smaller')
  assert.equal(await card('tasks').getAttribute('data-layout-version'),'1')
  const timerAfter = await page.evaluate(async () => (await import('/src/services/index.ts')).timerService.get())
  assert.equal(timerAfter.id,timerBefore.id); assert.equal(timerAfter.status,'running')
  await submit('Make Timer smaller','error')
  assert.match((await doc()).turns.at(-1).reply,/No smaller/)
  await card('outline').getByRole('button',{name:'Open Layout continuity',exact:true}).click()
  await page.getByLabel('Note body',{exact:true}).fill('Edited while arranging')
  await page.evaluate(async () => {
    window.layoutEditorNode=document.querySelector('[aria-label="Note body"]')
    const s=await import('/src/services/index.ts'),{workspaceDocumentStore}=await import('/src/services/workspaceDocumentStore.ts'),{applyInstanceOperations}=await import('/src/domain/workspaceDocument.ts')
    const store=workspaceDocumentStore(s.browserDatabase),doc=store.getSnapshot().document
    store.save(applyInstanceOperations(doc,[{type:'resize',widget:'outline',version:2},{type:'move',widget:'outline',position:'left-of',relativeTo:'tasks'}],()=>{throw new Error('Unexpected creation')}))
  })
  assert.equal(await page.getByLabel('Note body',{exact:true}).inputValue(),'Edited while arranging')
  assert.equal(await page.evaluate(()=>window.layoutEditorNode===document.querySelector('[aria-label="Note body"]')),true)
  await page.getByRole('dialog').getByRole('button',{name:'Close',exact:true}).last().click()
  await submit('Use Notes version 1')
  const beforePinRows=(await doc()).rows
  await card('outline').getByRole('button',{name:'Pin Notes',exact:true}).click()
  const pinned=await doc(), note=pinned.pins[0]
  assert.deepEqual(pinned.rows,beforePinRows)
  await submit('Move Notes above Tasks')
  assert.ok((await card('outline').boundingBox()).y < (await card('tasks').boundingBox()).y)
  const beforeUnpinRows=(await doc()).rows
  await card('outline').getByRole('button',{name:'Unpin Notes',exact:true}).click()
  assert.deepEqual((await doc()).rows,beforeUnpinRows)
  await submit('Move Calendar to the top')
  assert.equal((await doc()).rows[0][0],(await doc()).active.find(w=>w.widgetType==='calendar').instanceId)
  await submit('Put Timer left of Tasks')
  const desktopRows=(await doc()).rows
  const callCount=requests.length
  await page.getByRole('button',{name:'Hide sidebar',exact:true}).click()
  assert.deepEqual((await doc()).rows,desktopRows)
  await page.setViewportSize({width:390,height:844})
  await page.waitForFunction(()=>document.documentElement.scrollWidth<=window.innerWidth)
  timerBox=await card('quick-timer').boundingBox(); taskBox=await card('tasks').boundingBox()
  assert.ok(timerBox.y<taskBox.y)
  assert.deepEqual((await doc()).rows,desktopRows)
  await page.setViewportSize({width:1440,height:1000})
  await page.waitForFunction(()=>{const a=document.querySelector('[data-workspace-component="quick-timer"]').getBoundingClientRect(),b=document.querySelector('[data-workspace-component="tasks"]').getBoundingClientRect();return Math.abs(a.y-b.y)<2})
  assert.equal(requests.length,callCount)
  await submit('Use Tasks version 2')
  await page.getByRole('button',{name:'Workspace options'}).click()
  await page.getByRole('menuitem',{name:'Undo layout',exact:true}).click()
  assert.equal(await card('tasks').getAttribute('data-layout-version'),'1')
  await page.reload()
  await card('tasks').waitFor()
  assert.equal((await doc()).active.find(w=>w.widgetType==='tasks').instanceId,taskId)
  assert.equal((await doc()).active.find(w=>w.widgetType==='tasks').viewState.taskView,'kanban')
  assert.equal((await doc()).active.find(w=>w.instanceId===note.instanceId).layoutVersion,1)
  assert.deepEqual((await doc()).rows,desktopRows)
  assert.deepEqual(errors,[])
  await page.screenshot({path:'/tmp/orlo-widget-layout.png',fullPage:true})
  console.log('PASS: numbered versions, AI canvas metrics, relative positioning, small tool caps, pin movement, timer continuity, mobile stacking, undo and reload')
} finally { await browser.close(); await server.close() }
