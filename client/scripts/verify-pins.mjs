  assert.equal(await active().locator('.widget-outline').count(), 0)
  const originalIds = await page.locator('[data-pin-id]').evaluateAll(nodes => nodes.map(n => n.dataset.pinId))
  await goal('Prepare tomorrow Westbridge meeting')
  assert.equal(await active().locator('.widget-tasks .shared-task-row').count(), 2)
  assert.equal(await pinned('tasks').locator('.shared-task-row').count(), 1)
  assert.equal(await pinned('outline').getByRole('textbox', { name: 'Meeting agenda' }).inputValue(), 'Original Northstar agenda')
  await pinned('tasks').getByRole('textbox', { name: 'Search tasks' }).fill('mobile')
  assert.equal(await active().getByRole('textbox', { name: 'Search tasks' }).inputValue(), '')
  await pinned('outline').getByRole('textbox', { name: 'Meeting agenda' }).fill('Edited from retained Northstar view')
  await pinned('outline').getByRole('button', { name: 'Save draft', exact: true }).click()
  await page.reload()
  await waitForPins(2)
  assert.deepEqual(await page.locator('[data-pin-id]').evaluateAll(nodes => nodes.map(n => n.dataset.pinId)), originalIds)
  assert.equal(await pinned('tasks').getByRole('textbox', { name: 'Search tasks' }).inputValue(), 'mobile')
  assert.equal(await active().getByRole('textbox', { name: 'Meeting agenda' }).inputValue(), 'Review launch assets\nConfirm owners\nAgree delivery dates')
  await goal('Investigate Northstar usage')
  await active().locator('.widget-usage').getByRole('button', { name: /^Pin Usage/ }).click()
  await waitForPins(3)
  await goal('Investigate Westbridge usage')
  assert.match(await active().locator('.widget-usage').innerText(), /Westbridge/)
  assert.match(await pinned('usage').innerText(), /Northstar/)
  assert.doesNotMatch(await pinned('usage').innerText(), /Westbridge/)
  await page.reload()
  await waitForPins(3)
  assert.match(await pinned('usage').innerText(), /Northstar/)
  await pinned('usage').getByRole('button', { name: 'Why show Usage?' }).click()
  assert.match(await pinned('usage').innerText(), /northstar original evidence/)
  await page.evaluate(async () => { const { usageObservationService } = await import('/src/services/index.ts'); usageObservationService.update('atlas-2026-10-11-mobile', { sessions: 421 }) })
  assert.match(await pinned('usage').innerText(), /Supporting records changed/)
