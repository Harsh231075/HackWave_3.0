  console.log('PASS: scoped pins, deduplication, independent filters/drafts, reload IDs, three goals, reset/clear, dedicated views, manual usage selection, six-pin cap, deletion/undo, keyboard focus, mobile, calendar date isolation, gallery controls and legacy parser; no browser errors')
