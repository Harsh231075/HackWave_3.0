  await active().locator('.widget-recommendation').getByRole('button', { name: /^Pin Suggestions/ }).click()
  await waitForPins(4)
  await goal('Prepare tomorrow Westbridge meeting')
  assert.match(await pinned('recommendation').innerText(), /Resolve the onboarding blocker/)
  await options('Reset layout')
  await waitForPins(4)
  assert.equal(await active().locator('.widget-chart').count(), 1)
  await page.goto(`${base}/tasks`)
  assert.equal(await retained().count(), 0)
  await page.locator('.widget-tasks').getByRole('textbox', { name: 'Search tasks' }).fill('launch')
  await page.locator('.widget-tasks').getByRole('button', { name: /^Pin Tasks/ }).click()
