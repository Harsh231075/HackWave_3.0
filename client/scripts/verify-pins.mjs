  await page.keyboard.press('Enter')
  await waitForPins(5)
  assert.equal(await page.locator('main.generated-canvas').evaluate(n => document.activeElement === n), true)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.mouse.move(0, 0)
  await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await options('Clear pins')
  await waitForPins(0)
  await page.reload()
  assert.equal(await retained().count(), 0)
  // Pin a calendar date and verify navigation stays local to the retained view.
  await page.goto(`${base}/planner`)
