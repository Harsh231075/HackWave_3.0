import assert from 'node:assert/strict'
import { createServer } from 'vite'
const { chromium } = await import(process.env.ORLO_PLAYWRIGHT_MODULE || 'playwright')
const server = await createServer({ server: { host:'127.0.0.1', port:0 } })
await server.listen()
const browser = await chromium.launch({headless:true,...(process.env.ORLO_CHROME_PATH ? {executablePath:process.env.ORLO_CHROME_PATH} : {})})
try {
 const page = await browser.newPage({viewport:{width:1440,height:1000}})
 const errors=[];page.on('pageerror',error=>errors.push(error.message))
 const base='http://127.0.0.1:'+server.httpServer.address().port
 await page.goto(base+'/tasks')
 await page.getByLabel('Selected project').waitFor()
 assert.equal(await page.locator('[data-task-view] article').count(),0)
 await page.getByRole('button',{name:'New task',exact:true}).click()
 await page.getByLabel('Task title',{exact:true}).fill('My first task')
 await page.getByLabel('Owner',{exact:true}).fill('Me')
 await page.getByRole('button',{name:'Create task',exact:true}).click()
 await page.getByRole('button',{name:'Edit My first task',exact:true}).waitFor()
 await page.getByRole('button',{name:'Manage projects',exact:true}).click()
 await page.getByLabel('Project name',{exact:true}).fill('Second project')
 await page.getByRole('button',{name:'Create project',exact:true}).click()
 assert.equal(await page.getByRole('button',{name:'Edit My first task',exact:true}).count(),0)
 await page.reload()
 assert.equal(await page.getByLabel('Selected project').inputValue(),await page.evaluate(async()=> (await import('/src/services/index.ts')).projectDataService.selectedId()))
 await page.goto(base+'/notes')
 await page.getByRole('button',{name:'Notes library',exact:true}).click()
 await page.getByLabel('Note name').fill('New project note')
 await page.getByRole('button',{name:'Create note',exact:true}).click()
 await page.getByRole('button',{name:'Close',exact:true}).click()
 await page.getByRole('button',{name:'Settings',exact:true}).click()
 await page.getByRole('button',{name:'Reset local data',exact:true}).click()
 await page.getByRole('button',{name:'Confirm reset local data',exact:true}).click()
 await page.getByRole('button',{name:'Settings',exact:true}).click()
 await page.getByRole('button',{name:'Seed sample data',exact:true}).click()
 await page.goto(base+'/tasks')
 const ids=await page.evaluate(async()=>{const {projectDataService}=await import('/src/services/index.ts');return projectDataService.projects.list().map(p=>({id:p.id,name:p.name}))})
 const beforeCanvas=await page.evaluate(()=>JSON.parse(localStorage.getItem('orlo-browser-db-v1')).collections.workspaceDocument)
 await page.getByLabel('Selected project').selectOption(ids.find(p=>p.name==='Website launch').id)
 await page.getByRole('button',{name:'Edit Resolve launch blocker',exact:true}).waitFor()
 await page.getByLabel('Task view',{exact:true}).click()
 await page.getByRole('option',{name:'Kanban',exact:true}).click()
 assert.deepEqual(await page.evaluate(()=>JSON.parse(localStorage.getItem('orlo-browser-db-v1')).collections.workspaceDocument),beforeCanvas)
 await page.getByLabel('Selected project').selectOption(ids.find(p=>p.name==='Mobile onboarding').id)
 assert.equal(await page.getByRole('button',{name:'Edit Resolve launch blocker',exact:true}).count(),0)
 await page.getByRole('button',{name:'Edit Review activation problems',exact:true}).waitFor()
 assert.equal(await page.locator('[data-task-view="list"]').count(),1)
 await page.getByLabel('Selected project').selectOption(ids.find(p=>p.name==='Website launch').id)
 assert.equal(await page.locator('[data-task-view="kanban"]').count(),1)
 await page.getByLabel('Selected project').selectOption(ids.find(p=>p.name==='Mobile onboarding').id)
 await page.goto(base+'/meetings')
 assert.equal(await page.getByText('Website launch review',{exact:true}).count(),0)
 await page.reload()
 await page.getByLabel('Selected project').waitFor()
 const context=await browser.newContext();const legacy=await context.newPage()
 await legacy.goto(base+'/tasks')
 await legacy.evaluate(()=>{localStorage.setItem('gogpt-workspace-v1','{');localStorage.setItem('orlo-browser-db-v1',JSON.stringify({version:1,collections:{projects:[]}}))})
 await legacy.reload()
 await legacy.getByRole('heading',{name:'Local data needs a reset'}).waitFor()
 await legacy.getByRole('button',{name:'Settings',exact:true}).click()
 await legacy.getByRole('button',{name:'Reset local data',exact:true}).click()
 await legacy.getByRole('button',{name:'Confirm reset local data',exact:true}).click()
 await legacy.getByLabel('Selected project').waitFor()
 assert.deepEqual(errors,[])
 console.log('PASS: empty Default project, task creation/isolation, notes, project reload, reset/seed, linked meetings, legacy recovery; no page errors')
 await context.close()
} finally { await browser.close(); await server.close() }
